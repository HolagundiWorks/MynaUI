// Generates the per-app theme files from the templates, so there is one place to change how a theme is built.
//   node tools/make-variants.mjs
// Each app has an accent from the suite palette (docs/BRANDING.md in O-Studio): O-Studio Ember, O-Draft Midnight,
// O-Form Grove, O-CoreOp Dusk. The accents are in Themes/SuiteAccent.<Name>.xaml.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "O.Ui", "Themes");

const accents = {
  Orange: { app: "O-Studio", accent: "#B83E16", hover: "#A03212", pressed: "#8C2A10", text: "#B83E16", wash: "#F8E8E0", on: "#FFFFFF" },
  Mirage: { app: "O-Draft", accent: "#102C80", hover: "#0C2470", pressed: "#081C60", text: "#102C80", wash: "#E4E8F8", on: "#FFFFFF" },
  Sea: { app: "O-Form", accent: "#166040", hover: "#125236", pressed: "#0E422C", text: "#166040", wash: "#E4F0EA", on: "#FFFFFF" },
  Sand: { app: "O-CoreOp", accent: "#5630A0", hover: "#4A289A", pressed: "#3E2080", text: "#5630A0", wash: "#EEE8F8", on: "#FFFFFF" },
};

for (const [name, a] of Object.entries(accents)) {
  fs.writeFileSync(
    path.join(root, `SuiteAccent.${name}.xaml`),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- The accent of ${a.app}. Fills and marks use SuiteAccent; text in the accent colour uses SuiteAccentText; SuiteOnAccent is the text on a fill. Generated by tools/make-variants.mjs. -->
<ResourceDictionary
    xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
    <Color x:Key="SuiteAccent">${a.accent}</Color>
    <Color x:Key="SuiteAccentHover">${a.hover}</Color>
    <Color x:Key="SuiteAccentPressed">${a.pressed}</Color>
    <Color x:Key="SuiteAccentText">${a.text}</Color>
    <Color x:Key="SuiteAccentWash">${a.wash}</Color>
    <Color x:Key="SuiteOnAccent">${a.on}</Color>
</ResourceDictionary>
`,
  );
  for (const file of ["SuiteLight", "SuiteNavigation"]) {
    const template = fs.readFileSync(path.join(root, "templates", `${file}.template.xaml`), "utf8");
    const merge = `<ResourceDictionary.MergedDictionaries>
        <ResourceDictionary Source="ms-appx:///O.Ui/Themes/SuiteColors.xaml"/>
        <ResourceDictionary Source="ms-appx:///O.Ui/Themes/SuiteAccent.${name}.xaml"/>
    </ResourceDictionary.MergedDictionaries>`;
    fs.writeFileSync(path.join(root, `${file}.${name}.xaml`), template.replace("<!--MERGE-->", merge).replace("__APP__", a.app));
  }
  // Dark: accent first, then SuiteColors.Dark so the dark selection wash replaces the light one.
  {
    const template = fs.readFileSync(path.join(root, "templates", "SuiteDark.template.xaml"), "utf8");
    const merge = `<ResourceDictionary.MergedDictionaries>
        <ResourceDictionary Source="ms-appx:///O.Ui/Themes/SuiteAccent.${name}.xaml"/>
        <ResourceDictionary Source="ms-appx:///O.Ui/Themes/SuiteColors.Dark.xaml"/>
    </ResourceDictionary.MergedDictionaries>`;
    fs.writeFileSync(path.join(root, `SuiteDark.${name}.xaml`), template.replace("<!--MERGE-->", merge).replace("__APP__", a.app));
  }
}
console.log("generated", Object.keys(accents).join(", "));
